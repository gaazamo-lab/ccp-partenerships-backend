def _shift_dt(value: str | None, delta: dt.timedelta) -> dt.datetime | None:
    if not value:
        return None
    return dt.datetime.fromisoformat(value.replace("Z", "+00:00")) + delta


def _shift_date(value: str | None, delta: dt.timedelta) -> dt.date | None:
    moved = _shift_dt(value if value and "T" in value else (f"{value}T00:00:00Z" if value else None), delta)
    return moved.date() if moved else None


async def _stakeholder_ids(session) -> dict[str, uuid.UUID]:
    found: dict[str, uuid.UUID] = {}
    for key, (name, category) in STAKEHOLDERS.items():
        row = await session.scalar(select(Stakeholder).where(func.lower(Stakeholder.name) == name.lower()))
        if row is None:
            row = Stakeholder(name=name, category=category, owner="Nana Asante", status="Active", health="Healthy")
            session.add(row)
            await session.flush()
        found[key] = row.id
    return found


async def seed(session) -> None:
    if await session.scalar(select(KolProfile.id).where(func.lower(KolProfile.email) == MARKER_EMAIL)):
        return
    delta = dt.timedelta(days=(dt.date.today() - ANCHOR).days)
    stakeholders = await _stakeholder_ids(session)

    profile_ids: dict[str, uuid.UUID] = {}
    for raw in PROFILES:
        data = dict(raw)
        ref = data.pop("id")
        stk = data.pop("stakeholder_id")
        data["created_at"] = _shift_dt(data["created_at"], delta)
        data["updated_at"] = _shift_dt(data["updated_at"], delta)
        profile = KolProfile(stakeholder_id=stakeholders[stk] if stk else None, **data)
        session.add(profile)
        await session.flush()
        profile_ids[ref] = profile.id

    for raw in ENGAGEMENTS:
        data = dict(raw)
        data.pop("id")
        participation = data.pop("participation")
        if participation:
            participation = {**participation, "recordedAt": _shift_dt(participation["recordedAt"], delta).isoformat()}
        session.add(
            KolEngagement(
                kol_id=profile_ids[data.pop("kol_id")],
                scheduled_for=_shift_date(data.pop("scheduled_for"), delta),
                participation=participation,
                created_at=_shift_dt(data.pop("created_at"), delta),
                updated_at=_shift_dt(data.pop("updated_at"), delta),
                **data,
            )
        )

    content_ids: dict[str, uuid.UUID] = {}
    for raw in CONTENT:
        data = dict(raw)
        ref = data.pop("id")
        row = KolContent(
            kol_id=profile_ids[data.pop("kol_id")],
            due_date=_shift_date(data.pop("due_date"), delta),
            published_at=_shift_dt(data.pop("published_at"), delta),
            created_at=_shift_dt(data.pop("created_at"), delta),
            updated_at=_shift_dt(data.pop("updated_at"), delta),
            **data,
        )
        session.add(row)
        await session.flush()
        content_ids[ref] = row.id

    for raw in MENTIONS:
        data = dict(raw)
        data.pop("id")
        cid = data.pop("content_id")
        session.add(
            KolMediaMention(
                kol_id=profile_ids[data.pop("kol_id")],
                content_id=content_ids[cid] if cid else None,
                published_at=_shift_date(data.pop("published_at"), delta),
                **data,
            )
        )
    await session.flush()
